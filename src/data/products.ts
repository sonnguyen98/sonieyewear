// Merge override + lọc hidden + thêm sản phẩm mới
export const MERGED_PRODUCTS: Product[] = [
  // Sản phẩm gốc — bỏ qua những sản phẩm bị ẩn
  ...PRODUCTS
    .filter(p => !overrides[p.id]?.hidden)
    .map(p => ({
      ...p,
      ...(overrides[p.id] ?? {}),
      lensPackages: p.lensPackages,
    })),
  // Sản phẩm mới thêm từ Admin — áp dụng override (ảnh màu, tên, giá...)
  ...newProducts
    .filter(p => !overrides[p.id]?.hidden)
    .map(p => ({
      ...p,
      ...(overrides[p.id] ?? {}),
    })),
]

export function getProductBySlug(slug: string): Product | undefined {
  return MERGED_PRODUCTS.find(p => p.slug === slug)
}

export function getProductById(id: string): Product | undefined {
  return MERGED_PRODUCTS.find(p => p.id === id)
}

export function getBestSellers(limit = 6): Product[] {
  return MERGED_PRODUCTS.filter(p => p.isBestSeller).slice(0, limit)
}

export function getNewArrivals(limit = 6): Product[] {
  return MERGED_PRODUCTS.filter(p => p.isNew).slice(0, limit)
}

export function getRelatedProducts(product: Product, limit = 4): Product[] {
  return MERGED_PRODUCTS.filter(
    p => p.id !== product.id && (p.shape === product.shape || p.material === product.material)
  ).slice(0, limit)
}

